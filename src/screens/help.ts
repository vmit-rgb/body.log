const faqId = (group: number, item: number) => `faq-${group}-${item}`;

const faqItem = (group: number) => ([question, answer]: Answer, item: number) => `
  <div class="faq__item">
    <h3 class="faq__question">
      <button type="button" class="ctl accordion accordion--paragraph" aria-expanded="false" aria-controls="${faqId(group, item)}"><span class="accordion__title">${question}</span></button>
    </h3>
    <p class="t-2nd-regular" id="${faqId(group, item)}" hidden>${emoticonsHtml(answer)}</p>
  </div>`;

const faqGroup = ({ title, items }: FaqGroup, group: number) => `
  <section class="screen__section faq" aria-labelledby="faq-group-${group}">
    <h2 id="faq-group-${group}" class="t-h5">${title}</h2>
    ${items.map(faqItem(group)).join('')}
  </section>`;

function page(title: string, description: string, body: string): string {
  return `
    <div class="screen page">
      <section class="screen__section" aria-labelledby="page-title">
        <h1 id="page-title" class="t-h3">${title}</h1>
        <p class="t-2nd-regular muted">${description}</p>
      </section>
      ${body}
      ${FOOTER}
    </div>
    ${pagesBarMarkup()}`;
}

function show(host: HTMLElement, markup: string, actions: HelpActions): void {
  host.innerHTML = markup;
  wirePagesBar(host, actions);
}

const newsEntry = ({ version, changes }: NewsEntry) => `
  <article class="news__entry">
    <h2 class="t-2nd-bold">${version}</h2>
    <ul class="news__changes t-2nd-regular">${changes.map((change) => `<li>${change}</li>`).join('')}</ul>
  </article>`;

export function showWhatsNew(host: HTMLElement, actions: HelpActions): void {
  show(host, page('що нового', 'усі оновлення, найновіші зверху.', `
    <section class="screen__section news" aria-label="оновлення">${NEWS.map(newsEntry).join('')}</section>`), actions);
}

export function showHowToUse(host: HTMLElement, actions: HelpActions): void {
  show(host, page('як користуватись', 'коротко про те, що де лежить.', FAQ.map(faqGroup).join('')), actions);
  for (const group of host.querySelectorAll<HTMLElement>('.faq')) wireAccordions(group);
}
